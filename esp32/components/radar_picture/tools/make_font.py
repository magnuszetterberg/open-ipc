#!/usr/bin/env python3
"""Renders the radar picture's text font into font.cpp: printable ASCII as 8-bit coverage, two sizes.

Usage: esp32/components/radar_picture/tools/make_font.py [font.ttf] [bold.ttf]
  (default DejaVu Sans Mono, /usr/share/fonts/TTF/). Needs ffmpeg, for its drawtext (FreeType).

Run once; radar_font.cpp is committed, so firmware builds don't need ffmpeg or the font. DejaVu's licence (the
Bitstream Vera licence) allows embedding the rendered glyphs.
"""
import os
import subprocess
import sys
import tempfile

import numpy as np

regular = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/TTF/DejaVuSansMono.ttf"
bold = sys.argv[2] if len(sys.argv) > 2 else "/usr/share/fonts/TTF/DejaVuSansMono-Bold.ttf"
FIRST, LAST = 32, 126
SIZES = [("small", regular, 12), ("large", bold, 20)]


def render(font, size, text, width, height, y):
    """text drawn white on black by ffmpeg, as a numpy array of grey levels"""
    # From a file, with expansion off: no character needs escaping
    with tempfile.NamedTemporaryFile("w", suffix=".txt", encoding="utf-8") as f:
        f.write(text)
        f.flush()
        vf = (f"drawtext=fontfile={font}:fontsize={size}:fontcolor=white:x=0:y={y}:expansion=none:"
              f"textfile={f.name}")
        raw = subprocess.run(["ffmpeg", "-loglevel", "error", "-f", "lavfi", "-i", f"color=black:s={width}x{height}",
                              "-vf", vf, "-frames:v", "1", "-f", "rawvideo", "-pix_fmt", "gray", "-"],
                             check=True, capture_output=True).stdout
    return np.frombuffer(raw, np.uint8).reshape(height, width)


out = ["// Generated by tools/make_font.py from DejaVu Sans Mono (Bitstream Vera licence): don't edit.",
       '#include "radar_font.hpp"', ""]
for name, font, size in SIZES:
    height = size * 2
    # The advance: a monospace font's full blocks fill it exactly
    blocks = render(font, size, "█" * 20, size * 20, height, size // 2)
    cols = np.where(blocks.max(axis=0) > 128)[0]
    advance = round((cols[-1] - cols[0] + 1) / 20)
    # Each glyph alone, at the same baseline, in a cell of the advance's width. drawtext places a text by its
    # own top: a full block in front gives every glyph the same baseline, and the block's edge, which spills
    # into the glyph's cell, is taken away again.
    block = render(font, size, "█", advance * 2, height, size // 2).astype(int)
    cells = []
    for c in range(FIRST, LAST + 1):
        img = render(font, size, "█" + chr(c), advance * 2, height, size // 2).astype(int)
        cells.append(np.clip(img - block, 0, 255).astype(np.uint8)[:, advance:advance * 2])
    rows = np.where(np.max([cell.max(axis=1) for cell in cells], axis=0) > 0)[0]
    top, bottom = rows[0], rows[-1] + 1
    glyphs = np.array([cell[top:bottom] for cell in cells])
    h = bottom - top
    data = ",".join(str(v) for v in glyphs.reshape(-1))
    out.append(f"static const uint8_t {name}_glyphs[{glyphs.size}] = {{{data}}};")
    out.append(f"const radar_font radar_font_{name} = {{{advance}, {h}, {FIRST}, {LAST}, {name}_glyphs}};")
    out.append("")
    print(f"{name}: {size} px, cells {advance}x{h}", file=sys.stderr)

path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "radar_font.cpp")
with open(path, "w") as f:
    f.write("\n".join(out))
print(f"wrote {os.path.normpath(path)}", file=sys.stderr)
